
// Different types of waiting you should know

// For your interview, remember these:

// Type	Example	Purpose
// Auto-waiting	locator.click()	Waits for element to be actionable
// Assertion wait	expect(locator).toBeVisible()	Waits for expected condition
// Explicit condition wait	waitForSelector()	Wait for a specific selector
// URL wait	waitForURL()	Wait for navigation/URL
// Load-state wait	waitForLoadState()	Wait for page load state
// Hard wait	waitForTimeout()	Wait fixed amount of time